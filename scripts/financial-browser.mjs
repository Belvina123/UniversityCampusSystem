import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE);
if (!new URL(process.env.DATABASE_URL).pathname.endsWith('_test')) throw Error('Exige BD descartável');
process.env.NODE_ENV = 'production';
const { createApp } = await import('../apps/api/dist/app.js');
const { prisma } = await import('../apps/api/dist/lib/prisma.js');
const student = await prisma.user.findUniqueOrThrow({ where: { email: 'estudante@smartcampus.demo' } });
const server = createApp().listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
let browser;
const evidence = 'docs/integration-evidence';
try {
  const base = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  // A verificação usa apenas a aplicação local, sem descarregar a imagem externa do login.
  await page.route('https://images.unsplash.com/**', route => route.abort());
  await page.goto(base + '/login');
  await page.getByLabel('Email institucional').fill('financas@smartcampus.demo');
  await page.getByLabel('Password').fill('Finance123!');
  await page.getByRole('button', { name: 'Entrar no campus' }).click();
  await page.waitForURL('**/ops');
  await page.goto(base + '/financial');
  await page.getByLabel('Identificador do utilizador estudante').fill(student.id);
  await page.getByLabel('Descrição', { exact: true }).fill('Propina validada no Core');
  await page.getByLabel('Valor (MZN)', { exact: true }).fill('100');
  await page.getByLabel('Vencimento').fill('2099-01-01T12:00');
  await page.getByRole('button', { name: 'Registar dívida', exact: true }).click();
  await page.getByRole('cell', { name: 'Propina validada no Core', exact: true }).waitFor();
  await page.screenshot({ path: `${evidence}/finance-core.png`, fullPage: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const studentPage = await context.newPage();
  await studentPage.route('https://images.unsplash.com/**', route => route.abort());
  await studentPage.goto(base + '/login');
  await studentPage.getByLabel('Email institucional').fill('estudante@smartcampus.demo');
  await studentPage.getByLabel('Password').fill('Estudante123!');
  await studentPage.getByRole('button', { name: 'Entrar no campus' }).click();
  await studentPage.waitForURL('**/ops');
  await studentPage.goto(base + '/financial');
  await studentPage.getByRole('cell', { name: 'Propina validada no Core', exact: true }).waitFor();
  if (await studentPage.getByRole('button', { name: 'Registar dívida', exact: true }).count()) throw Error('Acção administrativa visível ao estudante');
  await studentPage.getByRole('button', { name: 'Contestar', exact: true }).click();
  await studentPage.getByLabel('Justificação').fill('Solicito revisão desta cobrança de demonstração.');
  await studentPage.getByRole('button', { name: 'Submeter contestação' }).click();
  await studentPage.getByRole('status').filter({ hasText: 'Operação concluída.' }).waitFor();
  await studentPage.screenshot({ path: `${evidence}/student-core.png`, fullPage: true });
  const createdDebtRow = page.getByRole('row').filter({ hasText: 'Propina validada no Core' });
  await createdDebtRow.getByRole('button', { name: 'Registar pagamento', exact: true }).click();
  await page.getByLabel('Referência').fill('ABC');
  assert.equal(await page.getByLabel('Referência').getAttribute('minlength'), '4');
  await page.getByLabel('Referência').fill(`BROWSER-${Date.now()}`);
  await page.getByRole('button', { name: 'Confirmar pagamento integral' }).click();
  await createdDebtRow.getByRole('cell', { name: 'REGULARIZADA', exact: true }).waitFor();
  await studentPage.reload();
  await studentPage.getByRole('cell', { name: 'REGULARIZADA', exact: true }).waitFor();
  assert.equal(await studentPage.getByRole('button', { name: 'Contestar', exact: true }).count(), 0);

  const teacherContext = await browser.newContext();
  const teacherPage = await teacherContext.newPage();
  await teacherPage.route('https://images.unsplash.com/**', route => route.abort());
  await teacherPage.goto(base + '/login');
  await teacherPage.getByLabel('Email institucional').fill('docente@smartcampus.demo');
  await teacherPage.getByLabel('Password').fill('Docente123!');
  await teacherPage.getByRole('button', { name: 'Entrar no campus' }).click();
  await teacherPage.waitForURL('**/ops');
  assert.equal(await teacherPage.locator('nav a[href="/financial"]').count(), 0);
  await teacherPage.goto(base + '/financial');
  await teacherPage.waitForURL('**/ops');
  writeFileSync(`${evidence}/browser.json`, JSON.stringify({ executedAt: new Date().toISOString(), success: true, checks: ['Login FINANCE oficial', 'Criação de dívida via UI', 'Login STUDENT oficial', 'Consulta da mesma dívida por User.id', 'Ausência de criação administrativa para STUDENT', 'Contestação via UI', 'Referência de pagamento com mínimo de 4 caracteres', 'Pagamento FINANCE reflectido na consulta STUDENT', 'TEACHER sem menu financeiro e acesso directo redireccionado'] }, null, 2) + '\n');
  console.log('Browser: login Core, criação e contestação financeiras confirmados.');
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); await prisma.$disconnect(); }
